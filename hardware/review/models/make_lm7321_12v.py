# -*- coding: utf-8 -*-
"""Write LM7321_12V.lib from the published National LM7321.MOD with its
10 VOLT TOTAL SUPPLY GROUP active instead of the 30 V group. The model's own
notice allows copies without modification, so the modified file is generated
here and not committed.

    python make_lm7321_12v.py
"""
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
src = io.open(os.path.join(HERE, "LM7321.MOD"), encoding="latin-1").read().splitlines()
out, mode = [], None
for ln in src:
    if ln.startswith("* 30 VOLT TOTAL SUPPLY GROUP"):
        mode = "30"
    elif ln.startswith("* END 30 V"):
        mode = None
    elif ln.startswith("* 10 VOLT TOTAL SUPPLY GROUP"):
        mode = "10"
    elif ln.startswith("* END 10 V"):
        mode = None
    if mode == "30" and ln and not ln.startswith("*"):
        ln = "*" + ln
    elif mode == "10" and ln.startswith("*") and not ln.startswith("* ") and len(ln) > 1 and ln[1] not in "*/":
        ln = ln[1:]
    out.append(ln)
txt = "\n".join(out).replace(".SUBCKT LM7321 3 4 5 2 1", ".SUBCKT LM7321_12V 3 4 5 2 1")
hdr = ("* LM7321_12V: the National LM7321 model with its 10 VOLT TOTAL SUPPLY GROUP active instead of the\n"
       "* published 30 V group, because the board runs the part from a single 12 V rail. Generated by\n"
       "* make_lm7321_12v.py from LM7321.MOD; the model file states that the groups may be interpolated.\n")
io.open(os.path.join(HERE, "LM7321_12V.lib"), "w", encoding="latin-1", newline="\n").write(hdr + txt + "\n")
print("written LM7321_12V.lib")
