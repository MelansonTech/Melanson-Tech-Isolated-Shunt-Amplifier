# -*- coding: utf-8 -*-
"""The proposal page for recommendation 1 (single-source reference trim):
markdown and a self-contained HTML page built from ref_trim.json, the two
proved schematics and the simulation figure. No number is typed here.

    python make_ref_trim_page.py
"""
import base64
import io
import json
import os
import re
import sys
from pathlib import Path

import markdown

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import ds_params as DS                                   # noqa: E402

DOCS = HERE.parent.parent.parent / "docs" / "design-review"
FIG = DOCS / "figures"
R = json.load(io.open(HERE / "ref_trim.json", encoding="utf-8"))
C = R["circuits"]
lm = DS.P["lm7321"]
si = DS.P["si8921"]


def f(x, n=2):
    return ("%%.%df" % n) % x


def span(c):
    return min(c["dv_mV"]), max(c["dv_mV"])


D = []
H = lambda l, t: D.append("#" * l + " " + t + "\n")
P = lambda t: D.append(t + "\n")


def T(head, rows):
    D.append("| " + " | ".join(head) + " |")
    D.append("|" + "|".join("---" for _ in head) + "|")
    for r in rows:
        D.append("| " + " | ".join(str(c) for c in r) + " |")
    D.append("")


def F(img, cap):
    D.append("![%s](figures/%s)\n\n*%s*\n" % (cap, img, cap))


H(1, "Single-source reference trim")
P("Recommendation 1 of the 2026-10-29 review, drawn and simulated. The two 6 V references (ISenseRTN, the chassis-bonded output return, and DiffAmpRef, the zero trim) are today generated by two separate 100 k / 100 k dividers and two buffers, with the trimmer in the second divider. The proposal keeps the first divider and buffer exactly as built and derives DiffAmpRef from ISenseRTN itself: a 100 Ω resistor in series, and the trim as a small current injected into that node from the existing 10 k trimmer through 100 k. Every number below is read from `hardware/review/sim/ref_trim.json`, written by `ref_trim.py`; the schematics are `ref_asbuilt.asc` and `ref_proposed.asc`, each netlisted by LTspice and compared element by element with the bench that produced the numbers.")

H(2, "As built")
F("ref_asbuilt.png", "Rev 3.1 reference section as built: two dividers, R28 (100 Ω) inside the second, R21 between the wiper and U9 (10 k on the board, 0 Ω on the sheet), C26 to GND.")
P("The weakness is not the dividers' tolerance, which the trim removes, but the two buffers' input currents working into two different impedances. An LM7321 input draws %s µA typical (up to %s µA), and the two inputs differ by up to %s nA. Into the second divider's 50 kΩ that difference is a %s mV shift between the references, more than the ±3 mV the trimmer spans, and its drift with temperature is not specified. With the board's 10 k R21 the model puts the whole span %s mV off zero." % (
    f(lm["ib_typ"] * 1e6, 1), f(abs(lm["ib_min"]) * 1e6, 0), f(lm["ios_max"] * 1e9, 0), f(lm["ios_max"] * 50e3 * 1e3, 0), f(C["asbuilt_r21_10k"]["mid_offset_mV"], 1)))

H(2, "Proposed")
F("ref_proposed.png", "Proposed: ISenseRTN through R21 (100 Ω, 0.1 %) to the U9 input; R33 (100 k) injects the trim current from the wiper of R28 (10 k across +12 and GND); C26 returns to ISenseRTN; R26 and R29 are deleted.")
P("DiffAmpRef = ISenseRTN + (V_wiper − ISenseRTN) × 100 / 100.1 k. Everything that moves ISenseRTN (the +12 rail, R22/R17, U5's offset and bias current) moves DiffAmpRef with it and drops out of the difference. What is left in the difference is U9's own offset and bias current into 100 Ω, and the trim network.")

H(2, "What the simulation shows")
rows = []
for k, nm in (("asbuilt_r21_10k", "as built, R21 = 10 k (board)"), ("asbuilt_r21_0", "as built, R21 = 0 (sheet)"), ("proposed", "proposed")):
    c = C[k]; lo, hi = span(c)
    ios = c["ios_term_mV"]
    rows.append([nm, "%s to %s" % (f(lo, 1), f(hi, 1)), f(c["mid_offset_mV"], 2), (f(ios, 1) + " mV") if abs(ios) >= 1 else (f(ios * 1e3, 0) + " µV"), "±" + f(abs(c["rail_term_uV"]["12.5"]), 0) + " µV", f(c["u9_loop"]["pm_deg"], 0) + "° at " + f(c["u9_loop"]["fc"] / 1e3, 0) + " kHz"])
T(["Circuit", "Trim span, mV", "Mid-travel offset, mV", "200 nA into the U9 input", "Rail ±0.5 V at full trim", "U9 loop margin"], rows)
P("**Simulated**, LM7321 vendor model at its 10 V group (its offset is −1.6 mV and its bias current −1.1 µA, both inside the datasheet limits, which is why the proposed span sits off-centre: that is the single buffer's offset showing, and it is what the trim is for). The as-built spans are ±3 mV; the proposed span is ±6 mV, chosen so that one buffer's full ±5 mV datasheet offset is inside it, where the as-built ±3 mV cannot cover two buffers' ±5 mV each (CALIBRATION.md already allows for fitting a 200 Ω trimmer when it will not null). The U9 loop sees the same 22 µF load and its margin does not move.")
F("ref-trim-sim.png", "Trim span against wiper position for the three cases, and the shift produced by 200 nA of bias-current imbalance at the U9 input (simulated).")

H(2, "Drift of the reference difference, from the datasheets")
b = R["budget_datasheet"]
T(["Term (at the reference node)", "As built, R21 = 0", "Proposed"],
  [["Buffer offset drift, 2.5 µV/°C typ each", "%s µV/°C (two buffers)" % f(b["asbuilt_r21_0"]["two Vos drifts, uV/C"], 1), "%s µV/°C (one buffer)" % f(b["proposed"]["one Vos drift, uV/C"], 1)],
   ["IOS maximum × source impedance, static", "%s mV (50 k)" % f(b["asbuilt_r21_0"]["IOS max x 50k"], 1), "%s µV (100 Ω)" % f(b["proposed"]["IOS max x 100 R"] * 1e3, 0)],
   ["Bias-current movement over temperature (20 % of typical)", "%s mV with 10 k R21; IOS drift unspecified" % f(b["asbuilt_r21_10k"]["Ib drift x 10k, 20 % of Ib, mV"], 1), "%s µV" % f(b["proposed"]["Ib drift x 100 R, 20 % of Ib, mV"] * 1e3, 0)],
   ["Trim resistors, 125 ppm/°C at full 6 mV trim", "about the same (the divider's R28 and R21)", "%s µV/°C" % f(b["proposed"]["trim resistors 125 ppm/C at 6 mV, uV/C"], 2)],
   ["Referred to the shunt (÷10) over ±20 °C", "up to 0.25 % of 100 mV, unspecified", "about %s %%" % f((b["proposed"]["one Vos drift, uV/C"] + b["proposed"]["trim resistors 125 ppm/C at 6 mV, uV/C"]) * 20 / 10 / 100e3 * 100, 3)]])
P("After the change the reference difference is no longer in the budget; the Si8921's own %s µV/°C maximum (%s µV over ±20 °C, %s %% of the 10 A range's full scale) is the next term and the one the isolator choice addresses." % (
    f(si["vos_drift_max"] * 1e6, 0), f(si["vos_drift_max"] * 20 * 1e6, 0), f(si["vos_drift_max"] * 20 / 0.1 * 100, 2)))

H(2, "BOM and sheet changes")
T(["Ref", "As built", "Proposed", "Note"],
  [["R26, R29", "100 k 0.1 %", "deleted", "the second divider"],
   ["R28", "CT94EW103 10 k in the BOM, 100 Ω fitted", "CT94EW103 10 k, across +12 and GND", "the BOM line becomes correct; 1.2 mA, 14 mW on a 0.5 W trimmer"],
   ["R21", "10 k (board) / 0 Ω (sheet), wiper to U9", "100 Ω 0.1 % 25 ppm, ISenseRTN to the U9 input", "same series as R17/R22"],
   ["R33", "-", "100 k 1 %, wiper to the U9 input", "new; its tolerance only scales the span"],
   ["C26", "100 nF to GND", "100 nF to ISenseRTN", "damps the wiper into the node; the pole is 16 kHz, the as-built 26 Hz filter is no longer needed because ISenseRTN's noise is common to both references"],
   ["U5, U9", "LM7321MF/NOPB (obsolete)", "unchanged by this proposal", "the part choice is recommendation 2"],
   ["R22, R17, C4, C10, C29, C30", "as built", "unchanged", ""]])
P("On the amplifier sheet: move R28's ends from R26/R29 to +12 and GND, replace R21's left end (the wiper) with ISenseRTN, add R33 from the wiper to the U9 non-inverting input, return C26 to ISenseRTN, delete R26 and R29. No board outline, connector or range change.")

H(2, "Not changed by this")
P("Noise (the Si8921 dominates), bandwidth, the isolation geometry, the reference absolute level (ISenseRTN still sits at +12 / 2 and moves with the rail, which the matched architecture tolerates), and the trim's proportionality to the rail (a ±0.5 V rail change moves a full 6 mV trim by ±%s µV, the same 4 %% as today)." % f(abs(C["proposed"]["rail_term_uV"]["12.5"]), 0))

md = "\n".join(D)
DOCS.mkdir(parents=True, exist_ok=True)
io.open(DOCS / "proposal-reference-trim.md", "w", encoding="utf-8", newline="\n").write(md)

CSS = io.open(HERE.parent / "make_page.py", encoding="utf-8").read().split('CSS = """')[1].split('"""')[0]
CSS = CSS.replace("<title>Isolated Shunt Amplifier Review</title>", "<title>Single-Source Reference Trim</title>")
html = markdown.markdown(md, extensions=["tables"])
html = re.sub(r'<p>(<img[^>]+>)</p>\s*<p><em>(.*?)</em></p>', r'<figure>\1<figcaption>\2</figcaption></figure>', html, flags=re.S)


def embed(m):
    p = DOCS / m.group(1)
    return 'src="data:image/png;base64,%s"' % base64.b64encode(open(p, "rb").read()).decode("ascii") if p.exists() else m.group(0)


html = re.sub(r'src="(figures/[^"]+)"', embed, html)
html = re.sub(r'<table>', '<div class="table-wrap"><table>', html)
html = re.sub(r'</table>', '</table></div>', html)
page = CSS + "<main>" + html + "</main>"
out = DOCS / "proposal-reference-trim.html"
io.open(out, "w", encoding="utf-8", newline="\n").write(page)
print("written", out, "%.2f MB" % (len(page.encode("utf-8")) / 1e6), "and the .md")
